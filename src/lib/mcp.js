// MCP (Model Context Protocol) tools.
//
// MCP servers are separate local programs — Word and PowerPoint editors,
// OneDrive/Outlook connectors, databases, anything — and a browser can't start
// a process, so every request goes through the dev-server proxy
// (scripts/mcp-proxy.mjs):
//
//   GET  /__mcp/servers   configured servers + live tool lists
//   POST /__mcp/config    save the list (persisted in .mcp.json next to the
//                         project, so env values never touch localStorage)
//   POST /__mcp/call      run one tool
//
// Tool names are prefixed `mcp__<server>__<tool>` so they can't collide with
// the built-in web/Anytype tools, and the prefix tells the user where a tool
// came from when the status line shows it running.

const BASE = "/__mcp";
const NAME_MAX = 64; // OpenAI function-name limit

export const isMcpTool = (name) => typeof name === "string" && name.startsWith("mcp__");

export const mcpToolLabel = (name) => {
  const parts = String(name).slice("mcp__".length).split("__");
  const tool = parts.slice(1).join("__") || name;
  return `running ${tool} on ${parts[0] || "mcp"}`;
};

const request = async (route, body) => {
  let res;
  try {
    res = await fetch(`${BASE}/${route}`, {
      method: body ? "POST" : "GET",
      headers: body ? { "Content-Type": "application/json" } : undefined,
      body: body ? JSON.stringify(body) : undefined,
    });
  } catch {
    throw new Error("MCP tools need the Aetheris dev server running (npm run dev).");
  }
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(data.error || `MCP request failed (HTTP ${res.status}).`);
  return data;
};

export const mcpListServers = async () => (await request("servers")).servers || [];
export const mcpSaveServers = async (servers) => request("config", { servers });
export const mcpRestart = async (server) => request("restart", { server });

const sanitize = (s) => String(s).replace(/[^A-Za-z0-9_-]/g, "_");

const functionName = (server, tool) =>
  `mcp__${sanitize(server)}__${sanitize(tool)}`.slice(0, NAME_MAX);

// ---------------------------------------------------------------------------
// JSON Schema cleanup
//
// MCP servers hand over their raw schemas (often generated by zod), which can
// carry $schema markers and $refs that /v1/chat/completions rejects outright —
// one bad schema fails the whole request. Resolve local refs, drop the rest,
// and remove any property that ends up with no type at all.
// ---------------------------------------------------------------------------
const cleanSchema = (schema) => {
  if (!schema || typeof schema !== "object") return { type: "object", properties: {} };
  let clone;
  try {
    clone = JSON.parse(JSON.stringify(schema));
  } catch {
    return { type: "object", properties: {} };
  }
  const defs = { ...(clone.$defs || {}), ...(clone.definitions || {}) };
  delete clone.$defs;
  delete clone.definitions;
  delete clone.$schema;

  const resolving = new Set();
  const walk = (node) => {
    if (Array.isArray(node)) return node.map(walk);
    if (!node || typeof node !== "object") return node;
    if (typeof node.$ref === "string") {
      const ref = node.$ref;
      if (resolving.has(ref)) return {};
      let target = null;
      const local = ref.startsWith("#/")
        ? ref
            .slice(2)
            .split("/")
            .reduce((acc, key) => (acc && typeof acc === "object" ? acc[key] : null), clone)
        : null;
      target = local || defs[ref.split("/").pop()] || null;
      const { $ref: _drop, ...siblings } = node;
      if (target && typeof target === "object") {
        resolving.add(ref);
        const merged = walk(target);
        resolving.delete(ref);
        return { ...merged, ...siblings };
      }
      return siblings; // unresolved — never leave a dangling $ref behind
    }
    const out = {};
    for (const [k, v] of Object.entries(node)) out[k] = walk(v);
    return out;
  };

  const cleaned = walk(clone);
  if (!cleaned || typeof cleaned !== "object") return { type: "object", properties: {} };

  // A property with no type (only a leftover $ref or description) is rejected
  // by the API — drop it, and drop it from `required` too.
  const isTyped = (v) =>
    v && typeof v === "object" && (v.type || v.enum || v.oneOf || v.anyOf || v.allOf || v.items || v.properties);
  if (cleaned.properties && typeof cleaned.properties === "object") {
    for (const key of Object.keys(cleaned.properties)) {
      if (!isTyped(cleaned.properties[key])) delete cleaned.properties[key];
    }
    if (Array.isArray(cleaned.required)) {
      cleaned.required = cleaned.required.filter((k) => cleaned.properties[k]);
      if (!cleaned.required.length) delete cleaned.required;
    }
  }
  if (cleaned.type === "object" && !cleaned.properties) cleaned.properties = {};
  if (!cleaned.type && !cleaned.properties && !cleaned.enum && !cleaned.items && !cleaned.oneOf && !cleaned.anyOf) {
    return { type: "object", properties: {} };
  }
  return cleaned;
};

// ---------------------------------------------------------------------------
// For the tool loop: build every enabled server's tools into OpenAI function
// tools and return a dispatcher for their calls. Returns an empty tool list
// (and a dispatcher that reports why) when no server is configured — or when
// the dev server isn't reachable at all, so chats still work.
// ---------------------------------------------------------------------------
export const mcpChatTools = async () => {
  const none = {
    servers: [],
    tools: [],
    run: async () => ({ error: "No MCP servers are configured." }),
  };
  let servers;
  try {
    servers = await mcpListServers();
  } catch {
    return { ...none, run: async () => ({ error: "The MCP proxy isn't reachable — is the dev server running?" }) };
  }

  const tools = [];
  const byName = new Map();
  const active = [];
  for (const s of servers) {
    if (s.enabled === false || !s.tools?.length) continue;
    active.push(`${s.name} (${s.tools.length} tools)`);
    for (const t of s.tools) {
      const name = functionName(s.name, t.name);
      if (byName.has(name)) continue;
      byName.set(name, { server: s.name, tool: t.name });
      tools.push({
        type: "function",
        function: {
          name,
          description:
            String(t.description || `Run ${t.name} on the ${s.name} MCP server.`).slice(0, 500) +
            ` [MCP server: ${s.name}]`,
          parameters: cleanSchema(t.inputSchema),
        },
      });
    }
  }

  return {
    servers: active,
    tools,
    run: async (name, args = {}) => {
      const hit = byName.get(name);
      if (!hit) return { error: `Unknown tool “${name}”.` };
      try {
        const r = await request("call", { ...hit, args });
        return r.ok ? { result: r.text } : { error: r.error };
      } catch (e) {
        return { error: e.message };
      }
    },
  };
};
